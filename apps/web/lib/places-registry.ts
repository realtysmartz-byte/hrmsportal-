/**
 * Checks if query matches any "Sector X" pattern and generates instant accurate coordinates
 */
export function matchSectorQuery(query: string): PlaceItem | null {
  const match = query.match(/(?:sec|sector)\s*([0-9]{1,3})([a-z]?)/i);
  if (!match) return null;
  const num = parseInt(match[1], 10);
  const suffix = (match[2] || "").toUpperCase();

  const known = SECTOR_COORDS_MAP[num];
  const name = `Sector ${num}${suffix}`;
  const sub = known?.subLoc ? ` (${known.subLoc})` : "";
  const displayName = `${name}${sub}, Gurugram, Haryana`;

  let lat = known?.lat;
  let lng = known?.lng;

  if (!lat || !lng) {
    if (num <= 23) {
      lat = 28.49; lng = 77.02;
    } else if (num <= 57) {
      lat = 28.44; lng = 77.06;
    } else if (num <= 79) {
      lat = 28.39; lng = 77.03;
    } else if (num <= 95) {
      lat = 28.40; lng = 76.95;
    } else {
      lat = 28.50; lng = 77.00;
    }
  }

  return {
    name,
    displayName,
    lat,
    lng,
    address: `${name}, Gurugram, Haryana 122001`,
    tag: "Gurugram Sector",
  };
}

